# GM8 strings have no escapes and may span lines.
SKIP_RE = re.compile(r'//[^\n]*|/\*.*?\*/|"[^"]*"|\'[^\']*\'', re.S)
CODE_TAG_RE = re.compile(
    r'(<argument kind="STRING">)(.*?)(</argument>)'
    r"|(<creationCode>)(.*?)(</creationCode>)",
    re.S,
)


def word_re(words):
    return re.compile(
        r"\b(" + "|".join(sorted(map(re.escape, words), key=len, reverse=True)) + r")\b"
    )


class Rewriter:
    def __init__(self, renames):
        self.rename_re = word_re(renames)
        self.renames = renames

    def code(self, text):
        out, last = [], 0
        for m in SKIP_RE.finditer(text):
            out += [self.rename_re.sub(lambda r: self.renames[r.group(1)], text[last : m.start()]), m.group(0)]
            last = m.end()
        out.append(self.rename_re.sub(lambda r: self.renames[r.group(1)], text[last:]))
        return "".join(out)


def apply_source_patches(out):
    # The repo source stays identical to the GM8 game; every hand-written
    # ENIGMA fix lives in patches/, applied in order to the build copy.
    for patch in sorted(PATCH_DIR.glob("*.patch")):
        with patch.open("rb") as f:
            result = subprocess.run(
                ["patch", "-s", "-p3", "--binary", "--forward",
                 "--no-backup-if-mismatch", "-r", "-", "-d", str(out)],
                stdin=f,
            )
        if result.returncode:
            sys.exit(f"prebuild: {patch.name} does not apply; refresh it against Source/gg2")


def apply_patches(out, patches):
    for rel, old, new in patches:
        path = out / rel
        text = path.read_text(encoding="utf-8")
        if text.count(old) != 1:
            sys.exit(f"prebuild: patch for {rel} matched {text.count(old)} times")
        path.write_text(text.replace(old, new), encoding="utf-8")


def drop_scripts(out, names):
    for name in names:
        (path,) = (out / "Scripts").rglob(f"{name}.gml")
        path.unlink()
        listing = path.parent / "_resources.list.xml"
        text = listing.read_text(encoding="utf-8")
        listing.write_text(
            text.replace(f'  <resource name="{name}" type="RESOURCE"/>\n', ""), encoding="utf-8"
        )


def add_script_group(out, group_name, scripts):
    group = out / "Scripts" / group_name
    group.mkdir()
    for name, code in scripts.items():
        (group / f"{name}.gml").write_text(code)
    (group / "_resources.list.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n<resources>\n'
        + "".join(f'  <resource name="{n}" type="RESOURCE"/>\n' for n in scripts)
        + "</resources>\n"
    )
    top = out / "Scripts" / "_resources.list.xml"
    text = top.read_text(encoding="utf-8")
    top.write_text(
        text.replace(
            "<resources>\n",
            f'<resources>\n  <resource name="{group_name}" type="GROUP"/>\n',
            1,
        ),
        encoding="utf-8",
    )


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("src", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument(
        "--stub-extensions",
        action="store_true",
        help="add return-0 scripts for native extensions",
    )
    ap.add_argument("--headless", action="store_true", help="build for widgets None")
    ap.add_argument(
        "--faucet-src",
        type=Path,
        help="Faucet-Networking-Extension checkout; bind libfaucetnet.so",
    )
    args = ap.parse_args()
    helpers = HEADLESS_HELPERS if args.headless else {}

    if args.out.exists():
        shutil.rmtree(args.out)
    shutil.copytree(args.src, args.out)
    apply_source_patches(args.out)

    renames = dict(RENAMES)
    renames.update({name: helper for name, (helper, _) in helpers.items()})
    renames.update({f: "fct_" + f for f in FAUCET})
    rw = Rewriter(renames)

    for f in sorted(args.out.rglob("*.gml")):
        f.write_text(rw.code(f.read_text(encoding="utf-8")), encoding="utf-8")

    def fix_tag(m):
        open_tag, body, close_tag = m.group(1, 2, 3) if m.group(1) else m.group(4, 5, 6)
        return open_tag + html.escape(rw.code(html.unescape(body)), quote=False) + close_tag

    for f in sorted(args.out.rglob("*.xml")):
        if f.name == "Constants.xml":
            continue
        original = f.read_text(encoding="utf-8")
        new = CODE_TAG_RE.sub(fix_tag, original)
        if new != original:
            f.write_text(new, encoding="utf-8")

    apply_patches(args.out, PATCHES)
    drop_scripts(args.out, DROP_SCRIPTS)
    add_script_group(args.out, "EnigmaHelpers", dict(helpers.values()) | COMPAT)
    bindings = gg2dll_scripts()
    if args.faucet_src:
        bindings |= faucet_scripts(args.faucet_src)
    add_script_group(args.out, "NativeBindings", bindings)
    if args.stub_extensions:
        stub = "// stub: native extension not built yet\nreturn 0;\n"
        names = [n for n in ["fct_" + f for f in FAUCET] if n not in bindings]
        names += OTHER_EXTENSIONS
        stubs = dict.fromkeys(names, stub) | STUB_OVERRIDES
        add_script_group(args.out, "ExtensionStubs", stubs)


if __name__ == "__main__":
    main()
