FAUCET_EXPORT_RE = re.compile(
    r'(?:DLLEXPORT|extern "C" __attribute__\(\(visibility\("default"\)\)\))\s+'
    r"(double|const char\s*\*|char\s*\*)\s*(\w+)\s*\(([^)]*)\)"
)


def faucet_scripts(faucet_src):
    """fct_* bindings to libfaucetnet.so (built by build.sh), from the exported
    C signatures in Faucet's source. Faucet functions that were GML scripts in
    the .gex (not used by GG2) raise an error instead."""
    exports = {}
    for f in sorted(Path(faucet_src, "faucet").rglob("*.cpp")):
        for m in FAUCET_EXPORT_RE.finditer(f.read_text(encoding="utf-8")):
            args = [a.strip() for a in m.group(3).split(",") if a.strip()]
            exports[m.group(2)] = (
                "ty_string" if "char" in m.group(1) else "ty_real",
                ["ty_string" if "char" in a else "ty_real" for a in args],
            )
    init = ["var dll;", 'dll = program_directory + "/libfaucetnet.so";']
    scripts = {}
    for name in FAUCET:
        gml = "fct_" + name
        if name not in exports:
            scripts[gml] = (
                f'show_error("{gml} is not available in ENIGMA builds", true);\n'
            )
            continue
        ret, args = exports[name]
        handle = f"global.{gml}_fn"
        types = "".join(f", {t}" for t in args)
        init.append(
            f'{handle} = external_define(dll, "{name}", dll_cdecl, {ret}, '
            f"{len(args)}{types});"
        )
        call_args = "".join(f", argument{i}" for i in range(len(args)))
        scripts[gml] = (
            "// ENIGMA-only binding, generated by prebuild.py\n"
            "if (!global.faucet_ready) faucet_init();\n"
            f"return external_call({handle}{call_args});\n"
        )
    init += [
        'external_call(external_define(dll, "dllStartup", dll_cdecl, ty_real, 0));',
        "global.faucet_ready = true;",
    ]
    scripts["faucet_init"] = "\n".join(init) + "\n"
    return scripts


def gg2dll_scripts():
    init = ["var dll;", 'dll = program_directory + "/libgg2dll.so";']
    scripts = {}
    for gml, (sym, ret, args) in GG2DLL_FUNCS.items():
        handle = f"global.{gml.lower()}_fn"
        init.append(
            f'{handle} = external_define(dll, "{sym}", dll_cdecl, {ret}, '
            f"{len(args)}, {', '.join(args)});"
        )
        call_args = "".join(f", argument{i}" for i in range(len(args)))
        scripts[gml] = (
            "// ENIGMA-only binding, generated by prebuild.py\n"
            "if (!global.gg2dll_ready) gg2dll_init();\n"
            f"return external_call({handle}{call_args});\n"
        )
    init.append("global.gg2dll_ready = true;")
    scripts["gg2dll_init"] = "\n".join(init) + "\n"
    return scripts


